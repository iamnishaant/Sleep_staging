"""
Phase 0: build the v1 golden set and the v1 execution manifest. Nothing is generated by a model here.

    python "AGENTIC AND SIMULATION/phase0/build_golden.py"

Reads only. Writes only into AGENTIC AND SIMULATION/results/golden/.

1. EXECUTION MANIFEST (v1). sha256 of every artefact that can change an output: staging checkpoint,
   every fitted table, packet builder, prompt builder, serializer, grammar, verifier, renderer, report
   model, llama-completion binary, plus the exact invocation and library versions. Its hash enters the
   run identity:  run_id = sha256(input_sha256 + policy_sha256 + execution_manifest_sha256).
2. REFERENCE 1: frozen packet evaluation. For the 31 dev nights, the frozen evaluation's own cached
   outputs (candidates/cache/Llama-Student/P1/), checked against today's prompt builder (prompt hash
   must match the cache key), re-verified with the frozen verifier, rendered, and hashed. Outcomes are
   recorded as they are, including the night that does not reach 5/5.
3. REFERENCE 2: legacy raw-EDF path. Recorded as a diagnostic (see legacy_raw_edf_probe.json); not a
   target for anything.
"""
import sys
sys.dont_write_bytecode = True
import hashlib
import json
import platform
import glob
from pathlib import Path

HERE = Path(__file__).resolve().parent
FOLDER = HERE.parent
ROOT = FOLDER.parent
OUT = FOLDER / "results" / "golden"
sys.path.insert(0, str(ROOT))


def sha_file(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def sha_text(s):
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    from deploy import server as S            # read-only: loads deploy/frozen.json
    from deploy.measure import LLAMA, MODELS
    from candidates import run as C
    from reference.prompts import build, prompt_hash
    from reference.run import DEV_MANIFEST
    from report import verify_report, render_report
    from report.evaluate import score_output
    import numpy, scipy, torch, mne

    S.verify_component_integrity()            # grammar / verifier / serializer match frozen.json
    frozen = json.loads((ROOT / "deploy" / "frozen.json").read_text(encoding="utf-8"))
    R = ROOT / "distillation"
    files = {
        "staging_checkpoint": R / "results/students/student_N4kd/student_best.pt",
        "reliability_table": R / "reliability_table.json",
        "sequence_decoding": R / "results/sequence_decoding.json",
        "night_confidence": R / "results/night_confidence.json",
        "derived_metric_reliability": R / "results/derived_metric_reliability.json",
        "n1_flag": R / "results/n1_flag.json",
        "gate3a_attribution_val": R / "results/_g3a_n4kd_val.json",
        "packet_builder": R / "build_packet.py",
        "sequence_decoder_code": R / "sequence_decode.py",
        "physiological_features": ROOT / "code/Phase2_47/physiological_features.py",
        "prompt_builder": ROOT / "reference/prompts.py",
        "serializer": ROOT / "report/serialize.py",
        "claim_schema": ROOT / "report/claim_schema.py",
        "grammar": ROOT / "report/claims.gbnf",
        "verifier_structure": ROOT / "report/verify_structure.py",
        "verifier_policy": ROOT / "report/verify_policy.py",
        "violations": ROOT / "report/violations.py",
        "renderer": ROOT / "report/render.py",
        "report_model_gguf": Path(MODELS["Llama-Student"]),
        "llama_completion_exe": Path(LLAMA),
    }
    missing = [k for k, p in files.items() if not Path(p).exists()]
    if missing:
        raise SystemExit(f"missing artefacts: {missing}")
    manifest = {
        "version": "v1",
        "description": "N4kd EEG staging + frozen Llama-3.2-3B-Student report model, llama-completion runtime",
        "artefacts": {k: {"path": str(Path(p).relative_to(ROOT)) if str(p).startswith(str(ROOT)) else str(p),
                          "sha256": sha_file(p)} for k, p in files.items()},
        "report_invocation": {"runtime_build": C.RUNTIME, "args_template": C.command("<model>", Path("<prompt>"),
                              "constrained", None)[1:], "n_predict": C.N_PREDICT, "context": C.CONTEXT,
                              "chat_template": "embedded in the GGUF", "prompt_id": C.PROMPT_ID},
        "frozen_json_hashes": frozen["components"] | {"model_sha256": frozen["model"]["sha256"]},
        "libraries": {"python": platform.python_version(), "numpy": numpy.__version__, "scipy": scipy.__version__,
                      "torch": torch.__version__, "mne": mne.__version__},
        "host": {"machine": platform.machine(), "system": platform.system(), "release": platform.release()},
    }
    if manifest["artefacts"]["report_model_gguf"]["sha256"] != frozen["model"]["sha256"]:
        raise SystemExit("report model sha256 differs from deploy/frozen.json")
    # hash only the parts that change outputs (host and library versions are recorded, not hashed)
    core = {k: manifest[k] for k in ("artefacts", "report_invocation")}
    core["artefacts"] = {k: v["sha256"] for k, v in core["artefacts"].items()}
    core["report_invocation"] = {k: v for k, v in core["report_invocation"].items() if k != "args_template"} | {
        "args": [a for a in manifest["report_invocation"]["args_template"] if a not in ("<model>", "<prompt>")]}
    manifest["execution_manifest_sha256"] = sha_text(json.dumps(core, sort_keys=True))
    (OUT / "execution_manifest_v1.json").write_text(json.dumps(manifest, indent=1))

    # ---- reference 1: frozen packet evaluation, 31 dev nights --------------------------------------
    rows = json.loads(Path(DEV_MANIFEST).read_text(encoding="utf-8"))
    pkt_dir = R / "results" / "phase2_dev_packets"
    (OUT / "html").mkdir(exist_ok=True)
    out = []
    for r in rows:
        rec = r["recording_id"]
        pk_path = pkt_dir / f"{rec}.json"
        packet = json.loads(pk_path.read_text(encoding="utf-8"))
        prompt = build(C.PROMPT_ID, packet)
        ph = prompt_hash(prompt)
        hits = glob.glob(str(ROOT / "candidates" / "cache" / "Llama-Student" / "P1" / f"{rec}__*.json"))
        entry = next((json.loads(Path(h).read_text(encoding="utf-8")) for h in hits
                      if json.loads(Path(h).read_text(encoding="utf-8"))["key"]["prompt_hash"] == ph), None)
        if entry is None:
            out.append({"recording_id": rec, "status": "MISSING_CACHED_OUTPUT", "prompt_sha256": ph})
            continue
        raw = entry["text"]
        res = score_output(raw, packet)
        html_sha = None
        if res.passed:
            html = render_report(verify_report(raw, packet), packet)
            (OUT / "html" / f"{rec}.html").write_text(html, encoding="utf-8")
            html_sha = sha_text(html)
        d = res.as_dict()
        out.append({"recording_id": rec, "cohort": r["cohort"], "status": "OK",
                    "packet_sha256": sha_file(pk_path), "prompt_sha256": ph,
                    "raw_output_sha256": sha_text(raw), "cache_file": Path(hits[0]).name,
                    "n_claims": d["n_claims"], "violations": d["violations"], "verifier_pass": d["passed"],
                    "mandatory_coverage": d["mandatory_coverage"], "mandatory_missing": d["mandatory_missing"],
                    "five_of_five": bool(d["passed"] and d["mandatory_coverage"] == 1.0),
                    "fidelity": [d["fidelity_matched"], d["fidelity_total"]], "html_sha256": html_sha,
                    "night_tier": d["tier"], "llm_wall_s_x86": entry.get("wall_s"),
                    "prompt_tokens": entry.get("prompt_tokens"), "output_tokens": entry.get("output_tokens"),
                    "staging_probs_sha256": sha_file(R / "results" / "probs_student_N4kd_val" / f"{rec}.npz")})
    ok = [x for x in out if x["status"] == "OK"]
    summary = {"reference": "1: frozen packet evaluation (v1)", "nights": len(out),
               "with_cached_output": len(ok),
               "verifier_pass": sum(x["verifier_pass"] for x in ok),
               "five_of_five": sum(x["five_of_five"] for x in ok),
               "not_five_of_five": [(x["recording_id"], x["mandatory_missing"], x["violations"]) for x in ok if not x["five_of_five"]],
               "fidelity": [sum(x["fidelity"][0] for x in ok), sum(x["fidelity"][1] for x in ok)],
               "execution_manifest_sha256": manifest["execution_manifest_sha256"]}
    (OUT / "reference1_frozen_packets_v1.json").write_text(json.dumps({"summary": summary, "nights": out}, indent=1))
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
